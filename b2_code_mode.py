"""Challenge B2 - Python-only, fixed-program Code Mode demonstration.

Goals:
  - Read hundreds of simulated log files using local Python tool calls.
  - Keep raw logs out of LLM requests.
  - Compare estimated native/raw vs aggregated prompt tokens.
  - Ask an LLM via the existing 9Router config to answer from findings.

This is a SAFE, fixed-program learning version of Code Mode. The LLM does
NOT generate executable Python code. Generating and running arbitrary LLM code
would require sandboxing beyond the scope of this Windows tutorial.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re
from typing import Any

# Existing B1 module; uses exactly the user's verified .env (9Router).
from main import OpenAIPlanner, ROOT, load_json, save_json

DATA_DIR = ROOT / "b2_data"
LOG_DIR = DATA_DIR / "logs"
QUESTION = "Lỗi nào xuất hiện nhiều nhất? Có bao nhiêu lần, file nào chứa nhiều lỗi nhất?"
SYSTEM = (
    "Bạn là một AI Agent phân tích LOG GIẢ LẬP. "
    "Chỉ dựa trên structured findings. "
    "Không suy diễn nguyên nhân gốc khi chỉ có các đếm lỗi. "
    "Trả lời bằng tiếng Việt, có thống kê số liệu và lưu ý hạn chế. "
    "Không yêu cầu hoặc giả vờ đã đọc raw logs."
)
RAW_MARKER = "RAW_ONLY_SENTINEL_B2"
ERROR_PATTERN = re.compile(r"\bERROR\s+code=([A-Z_]+)\b")


def estimate_tokens(text: str) -> int:
    """Estimate prompt tokens, not provider billing usage."""
    try:
        import tiktoken
        encoding = tiktoken.get_encoding("o200k_base")
        return len(encoding.encode(text))
    except ImportError:
        return max(1, len(text) // 4)


def generate(log_dir: Path = LOG_DIR, num_files: int = 100, lines_per_file: int = 120) -> dict[str, int]:
    """Create synthetic data only; does not touch a real backend or log file."""
    if num_files < 3 or lines_per_file < 50:
        raise ValueError("Need >=3 files and >=50 lines/file for the B2 demo.")
    log_dir.mkdir(parents=True, exist_ok=True)
    for old_file in log_dir.glob("service-*.log"):
        old_file.unlink()
    for file_id in range(num_files):
        rows = []
        for line_id in range(lines_per_file):
            timestamp = "2026-10-26T10:00:00Z"
            trace_id = f"{RAW_MARKER}_{file_id:03d}_{line_id:04d}"
            if (line_id + file_id) % 11 == 0:
                event = "ERROR code=REFRESH_RACE operation=refresh_session outcome=failed"
            elif (line_id + file_id) % 19 == 0:
                event = "ERROR code=UPSTREAM_TIMEOUT operation=http_request outcome=failed"
            elif (line_id + file_id) % 31 == 0:
                event = "ERROR code=DB_POOL_EXHAUSTED operation=db_query outcome=failed"
            else:
                event = "INFO code=OK operation=background_heartbeat outcome=success"
            rows.append(
                f"{timestamp} service=identity worker={file_id % 8} "
                f"trace={trace_id} {event} diagnostic=synthetic_data\n"
            )
        (log_dir / f"service-{file_id:03d}.log").write_text("".join(rows), encoding="utf-8")
    return {"files": num_files, "lines": num_files * lines_per_file}


class LocalLogTools:
    """Two allowlisted local tools. All file content remains inside Python."""

    def __init__(self, log_dir: Path):
        self.log_dir = log_dir.resolve()
        self.files_read = 0
        self.bytes_read = 0
        self.lines_read = 0

    def list_files(self, pattern: str = "*.log") -> list[Path]:
        # Fixed approved pattern; prevents accidental reading of other files.
        if pattern != "*.log":
            raise ValueError("Only '*.log' is allowed in this demo")
        return sorted(self.log_dir.glob(pattern))

    def read_file(self, path: Path) -> str:
        path = path.resolve()
        if not path.is_relative_to(self.log_dir) or path.suffix != ".log" or not path.is_file():
            raise ValueError("Outside approved B2 logs directory")
        text = path.read_text(encoding="utf-8")
        self.files_read += 1
        self.bytes_read += len(text.encode("utf-8"))
        self.lines_read += len(text.splitlines())
        return text


def run_code(tools: LocalLogTools) -> dict[str, Any]:
    """PRE-APPROVED CODE MODE PROGRAM. No raw log text is returned to the model.

    Compare slide 30: tools.list_files -> tools.read_file in loop -> aggregation
    -> top findings only. This runnable program is intentionally fixed, not
    arbitrarily generated by an LLM and executed on the user's PC.
    """
    counts: Counter[str] = Counter()
    per_file: Counter[str] = Counter()
    paths = tools.list_files("*.log")
    if not paths:
        raise FileNotFoundError("No B2 logs. Run 'python b2_code_mode.py generate' first.")
    for path in paths:
        # This content exists ONLY in local Python memory, not in model context.
        raw = tools.read_file(path)
        for line in raw.splitlines():
            match = ERROR_PATTERN.search(line)
            if match:
                counts[match.group(1)] += 1
                per_file[path.name] += 1
    return {
        "dataset": "synthetic local log data",
        "files_scanned": tools.files_read,
        "lines_scanned": tools.lines_read,
        "error_events": sum(counts.values()),
        "error_counts": [
            {"code": code, "count": count}
            for code, count in sorted(counts.items(), key=lambda v: (-v[1], v[0]))
        ],
        "top_5_files": [
            {"file": path, "errors": count}
            for path, count in sorted(per_file.items(), key=lambda v: (-v[1], v[0]))[:5]
        ],
        "note": "Counts only; does not prove root cause.",
    }


def build_model_prompt(question: str, findings: dict[str, Any]) -> str:
    return ("USER QUESTION: " + question + "\n"
            + "LOCAL CODE RESULTS (no raw log lines):\n"
            + json.dumps(findings, ensure_ascii=False, indent=2))


def analyze(log_dir: Path = LOG_DIR, data_dir: Path = DATA_DIR,
            question: str = QUESTION) -> tuple[dict[str, Any], dict[str, Any]]:
    tools = LocalLogTools(log_dir)
    findings = run_code(tools)
    compact_prompt = SYSTEM + "\n" + build_model_prompt(question, findings)

    # Native tool-calling comparison is ONLY AN OFFLINE ESTIMATE: DO NOT send this
    # raw prompt to the LLM. Summed per-file estimate avoids a huge string.
    baseline = estimate_tokens(SYSTEM + "\nUSER QUESTION: " + question)
    for path in tools.list_files("*.log"):
        baseline += estimate_tokens(path.read_text(encoding="utf-8"))
    compact = estimate_tokens(compact_prompt)
    metrics = {
        "files_read_by_runtime": tools.files_read,
        "raw_log_bytes_processed_locally": tools.bytes_read,
        "log_lines_processed_locally": tools.lines_read,
        "naive_raw_prompt_estimated_tokens": baseline,
        "code_mode_prompt_estimated_tokens": compact,
        "estimated_reduction_percent": round(100 * (1 - compact / baseline), 2),
        "estimate_only_not_real_api_usage": True,
        "raw_logs_sent_to_llm": False,
        "model_request_created": False,
    }
    data_dir.mkdir(parents=True, exist_ok=True)
    save_json(data_dir / "findings.json", findings)
    save_json(data_dir / "metrics.json", metrics)
    save_json(data_dir / "payload_to_llm.json", {
        "system": SYSTEM,
        "user": build_model_prompt(question, findings),
    })
    # If analyzing again, stale LLM answers MUST NOT count toward verify.
    (data_dir / "answer.json").unlink(missing_ok=True)
    print(f"Runtime read {tools.files_read} log files / {tools.lines_read} lines LOCALLY")
    print(f"Naive all-raw prompt estimate: {baseline} tokens")
    print(f"Code Mode compact prompt estimate: {compact} tokens")
    print(f"Estimated reduction: {metrics['estimated_reduction_percent']:.2f}%")
    print("Files written: b2_data/findings.json, metrics.json, payload_to_llm.json")
    print("No LLM called in 'analyze'; no raw log lines prepared for transmission.")
    return findings, metrics


def ask(data_dir: Path = DATA_DIR, planner: Any | None = None) -> str:
    """One inference call through B1's confirmed OpenAI-compatible 9Router adapter."""
    prompt_data = load_json(data_dir / "payload_to_llm.json")
    if RAW_MARKER in json.dumps(prompt_data):
        raise ValueError("Unsafe LLM input: a raw-log marker leaked into prompt")
    if not (data_dir / "findings.json").exists():
        raise FileNotFoundError("Run 'python b2_code_mode.py analyze' first.")
    if planner is None:
        planner = OpenAIPlanner()
    response = planner._ask_text(prompt_data["system"], prompt_data["user"])
    save_json(data_dir / "answer.json", {"response": response, "from": "findings_only"})
    metrics = load_json(data_dir / "metrics.json")
    metrics["model_request_created"] = True
    save_json(data_dir / "metrics.json", metrics)
    print("\n9Router Agent answer (from structured findings only):\n")
    print(response)
    return response


def verify(data_dir: Path = DATA_DIR) -> bool:
    missing = [f for f in ["findings.json", "metrics.json", "payload_to_llm.json", "answer.json"]
               if not (data_dir / f).exists()]
    if missing:
        print("B2 RESULT: FAIL - missing files:", ", ".join(missing))
        return False
    findings = load_json(data_dir / "findings.json")
    metrics = load_json(data_dir / "metrics.json")
    payload = load_json(data_dir / "payload_to_llm.json")
    answer = load_json(data_dir / "answer.json")
    checks = {
        ">= 50 log files processed locally": metrics["files_read_by_runtime"] >= 50,
        "raw log marker ABSENT from model prompt": RAW_MARKER not in json.dumps(payload),
        "full logs not passed to model": "diagnostic=synthetic_data" not in json.dumps(payload),
        "code mode estimated prompt smaller >= 80%": metrics["estimated_reduction_percent"] >= 80,
        "LLM response was obtained": bool(answer.get("response", "").strip()) and metrics["model_request_created"],
        "top error REFRESH_RACE counted": bool(findings["error_counts"]) and findings["error_counts"][0]["code"] == "REFRESH_RACE",
    }
    for name, passed in checks.items():
        print(("PASS" if passed else "FAIL") + " - " + name)
    success = all(checks.values())
    print("B2 RESULT:", "PASS" if success else "FAIL")
    return success


def main() -> None:
    parser = argparse.ArgumentParser(description="Challenge B2: Python Code Mode vs raw log context")
    parser.add_argument("command", choices=["generate", "analyze", "ask", "verify"])
    parser.add_argument("--files", type=int, default=100)
    parser.add_argument("--lines", type=int, default=120)
    args = parser.parse_args()
    if args.command == "generate":
        result = generate(num_files=args.files, lines_per_file=args.lines)
        print(f"Generated {result['files']} synthetic log files / {result['lines']} lines")
    elif args.command == "analyze":
        analyze()
    elif args.command == "ask":
        ask()
    elif args.command == "verify":
        if not verify():
            raise SystemExit(1)


if __name__ == "__main__":
    main()
